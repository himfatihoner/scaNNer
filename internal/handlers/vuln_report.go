// VulnDetail renders one vulnerability's detail-drawer fragment (report +
// PoC), fetched lazily by the Vulnerabilities page when a row is expanded. The
// page ships with empty drawers so it stays small; this endpoint does the
// per-vuln buildVulnReport work only on demand.
func (h *Handler) VulnDetail(w http.ResponseWriter, r *http.Request) {
	ws := h.activeWorkspace(r)
	if ws == nil {
		http.Error(w, "no active workspace", http.StatusBadRequest)
		return
	}
	id := r.URL.Query().Get("id")
	liteScans, _ := h.db.ListScansLite(ws.ID, "")
	vulns, _ := h.getVulnIndex(ws.ID, liteScans)
	for i := range vulns {
		if vulns[i].ID == id {
			h.render(w, "vuln_detail_inner", vulns[i])
			return
		}
	}
	http.NotFound(w, r)
}

// VulnExport serves a per-vulnerability (or multi/bulk) report in PDF or DOCX,
// TR or EN. Selection (first match wins): ids=<SCN,SCN,…> (checkbox multi-
// select, via GET or POST form) → all=1 (filtered bulk, honoring sev/module/q)
// → id=<SCN> (single). format=pdf|docx; lang=tr|en.
func (h *Handler) VulnExport(w http.ResponseWriter, r *http.Request) {
	ws := h.activeWorkspace(r)
	if ws == nil {
		http.Error(w, "no active workspace", http.StatusBadRequest)
		return
	}
	liteScans, _ := h.db.ListScansLite(ws.ID, "")
	vulns, _ := h.getVulnIndex(ws.ID, liteScans)

	// FormValue reads either the query string (GET links: per-row id, all=1)
	// or a POST body (the "Export Selected" form, whose ids list can be long).
	_ = r.ParseForm()
	get := r.FormValue
	format := strings.ToLower(get("format"))
	if format != "docx" {
		format = "pdf"
	}
	lang := strings.ToLower(get("lang"))
	if lang != "en" {
		lang = "tr"
	}

	var selected []GlobalVuln
	fnameBase := "vulnerability"
	switch {
	case strings.TrimSpace(get("ids")) != "":
		// Multi-select: a comma-separated set of SCN ids. Emit in the page's
		// severity order (vulns is already sorted), not the click order.
		want := map[string]bool{}
		for _, id := range strings.Split(get("ids"), ",") {
			if id = strings.TrimSpace(id); id != "" {
				want[id] = true
			}
		}
		for _, v := range vulns {
			if want[v.ID] {
				selected = append(selected, v)
			}
		}
		fnameBase = fmt.Sprintf("vulnerabilities_%d", len(selected))
	case get("all") == "1":
		// sev may be a comma-separated set of ranks (multi-select filter), e.g. "4,3".
		sevSet := map[string]bool{}
		for _, s := range strings.Split(get("sev"), ",") {
			if s = strings.TrimSpace(s); s != "" {
				sevSet[s] = true
			}
		}
		mod := get("module")
		needle := strings.ToLower(strings.TrimSpace(get("q")))
		for _, v := range vulns {
			if len(sevSet) > 0 && !sevSet[itoa(v.SevRank)] {
				continue
			}
			if mod != "" && v.Module != mod {
				continue
			}
			if needle != "" {
				hay := strings.ToLower(v.Host + " " + v.Title + " " + v.Module + " " + strings.Join(v.CVEs, " "))
				if !strings.Contains(hay, needle) {
					continue
				}
			}
			selected = append(selected, v)
		}
		fnameBase = fmt.Sprintf("vulnerabilities_%d", len(selected))
	default:
		id := get("id")
		for _, v := range vulns {
			if v.ID == id {
				selected = append(selected, v)
				break
			}
		}
		if len(selected) == 1 {
			fnameBase = vulnFileBase(selected[0])
		}
	}

	if len(selected) == 0 {
		http.Error(w, "vulnerability not found (the index may still be building — reload the Vulnerabilities page and retry)", http.StatusNotFound)
		return
	}

	// separate=1 → one file per vulnerability, zipped (the "ayrı ayrı" bulk
	// option) instead of a single combined document.
	if get("separate") == "1" && len(selected) > 1 {
		h.exportVulnZip(w, selected, format, lang, fnameBase)
		return
	}

	reports := make([]VulnReport, 0, len(selected))
	for _, v := range selected {
		reports = append(reports, buildVulnReport(v, lang))
	}

	if format == "docx" {
		h.exportVulnDOCX(w, reports, lang, fnameBase)
		return
	}
	h.exportVulnPDF(w, reports, lang, fnameBase)
}
