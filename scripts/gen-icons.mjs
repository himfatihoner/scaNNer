// Generates internal/handlers/icons.go from the Lucide SVG sources in
// scripts/icons/ (https://lucide.dev, ISC license). Inline monochrome icons
// replace the old emoji .Icon() values + UI-chrome emoji, so iconography is
// crisp, consistent and theme-adaptive (stroke=currentColor).
//
//   Add an icon:  drop <name>.svg into scripts/icons/ then `node scripts/gen-icons.mjs`
//   (fetch a Lucide icon: curl -sL https://unpkg.com/lucide-static@0.544.0/icons/<name>.svg)

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'scripts/icons');
const OUT = path.join(ROOT, 'internal/handlers/icons.go');

const files = fs.readdirSync(SRC).filter(f => f.endsWith('.svg')).sort();
if (!files.length) throw new Error('no SVGs in ' + SRC);

const entries = [];
for (const f of files) {
  const name = f.replace(/\.svg$/, '');
  const svg = fs.readFileSync(path.join(SRC, f), 'utf8');
  const m = svg.match(/<svg[^>]*>([\s\S]*?)<\/svg>/);
  if (!m) throw new Error('no <svg> in ' + f);
  // Keep inner markup only (paths/circles/...); collapse whitespace BETWEEN tags
  // (never inside attributes, so path `d=` data is untouched).
  const inner = m[1].replace(/>\s+</g, '><').trim();
  if (inner.includes('`')) throw new Error('backtick in ' + f + ' breaks Go raw string');
  entries.push([name, inner]);
}

let go = `// Code generated by scripts/gen-icons.mjs from scripts/icons/*.svg. DO NOT EDIT.
// Icons: Lucide (https://lucide.dev) — ISC license.
package handlers

import (
\t"fmt"
\t"html/template"
\t"strings"
)

// iconPaths maps an icon name to its inline SVG inner markup. 24x24 viewBox,
// stroke=currentColor so each icon inherits the surrounding text color and
// adapts to light/dark with zero per-call styling.
var iconPaths = map[string]string{
`;
for (const [name, inner] of entries) go += `\t${JSON.stringify(name)}: \`${inner}\`,\n`;
go += `}

// renderIcon returns an inline <svg> for the named icon, sized and colored by
// the optional Tailwind class string (default "w-4 h-4"). An unknown name
// renders nothing, so a bad key can never emit broken markup. Registered in the
// template FuncMap as {{icon "name"}} / {{icon "name" "w-5 h-5 text-accent-400"}}.
func renderIcon(name string, class ...string) template.HTML {
\tinner, ok := iconPaths[name]
\tif !ok {
\t\treturn ""
\t}
\tcls := "w-4 h-4"
\tif len(class) > 0 && strings.TrimSpace(class[0]) != "" {
\t\tcls = class[0]
\t}
\treturn template.HTML(fmt.Sprintf(
\t\t\`<svg class=%q viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">%s</svg>\`,
\t\tcls, inner))
}
`;

fs.writeFileSync(OUT, go);
console.log('wrote', OUT, '—', entries.length, 'icons');
